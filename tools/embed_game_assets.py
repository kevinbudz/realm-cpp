#!/usr/bin/env python3
"""Generate the translation unit that compiles the runtime game assets into realm_client.

Embedded: every non-.as file under <flash-root>/src (the PNG, XML .dat, OTF and SWF files the client reads, and
the OBJ models, which are small) and every .mp3 under <sfx-root>, recursively. Each file becomes a byte array,
keyed "flash/<path under flash-root>" or "sfx/<path under sfx-root>". The output defines
realm::assets::embedded_file(key) (declared in realm/assets/AssetStore.hpp). Keys are sorted, so the output is
deterministic. Byte arrays rather than #embed: #embed is C++26 and warns under the project's C++20 flags.
"""
import argparse
from pathlib import Path


def embedded_files(flash_root, sfx_root):
    """(key, path) pairs in key order."""
    flash = [('flash/' + p.relative_to(flash_root).as_posix(), p)
             for p in (flash_root / 'src').rglob('*') if p.is_file() and p.suffix != '.as']
    sfx = [('sfx/' + p.relative_to(sfx_root).as_posix(), p) for p in sfx_root.rglob('*.mp3') if p.is_file()]
    entries = sorted(flash + sfx)
    for key, _ in entries:
        if '"' in key or '\\' in key or '\n' in key:
            raise ValueError(f'Asset key cannot be embedded: {key!r}')
    return entries


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--flash-root', type=Path, required=True)
    parser.add_argument('--sfx-root', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    flash_root, sfx_root = args.flash_root.resolve(), args.sfx_root.resolve()
    if not (flash_root / 'src').is_dir():
        raise SystemExit(f'Flash source not found: {flash_root}')
    if not sfx_root.is_dir():
        raise SystemExit(f'SFX directory not found: {sfx_root}')
    entries = embedded_files(flash_root, sfx_root)
    if not entries:
        raise SystemExit('No game assets to embed')

    lines = ['// Generated by tools/embed_game_assets.py from the Flash and SFX roots; do not edit.',
             '#include "realm/assets/AssetStore.hpp"',
             '#include <algorithm>',
             '#include <array>',
             '#include <cstddef>',
             '#include <optional>',
             '#include <span>',
             '#include <string_view>',
             'namespace realm::assets {',
             'namespace {']
    sizes = []
    for index, (key, path) in enumerate(entries):
        data = path.read_bytes()
        sizes.append(len(data))
        lines.append(f'// {key}')
        if data:
            lines.append(f'constexpr unsigned char file_{index}[] = {{')
            for start in range(0, len(data), 32):
                lines.append(','.join(f'0x{byte:02x}' for byte in data[start:start + 32]) + ',')
            lines.append('};')
        else:
            lines.append(f'constexpr unsigned char file_{index}[1] = {{0}};')
    lines.append('struct Entry { std::string_view key; const unsigned char* data; std::size_t size; };')
    lines.append(f'constexpr std::array<Entry, {len(entries)}> entries{{{{')
    for index, ((key, _), size) in enumerate(zip(entries, sizes)):
        lines.append(f'    {{"{key}", file_{index}, {size}}},')
    lines.append('}};')
    lines.append('}  // namespace')
    lines.append('std::optional<std::span<const unsigned char>> embedded_file(std::string_view key) {')
    lines.append('    const auto found = std::lower_bound(entries.begin(), entries.end(), key,')
    lines.append('                                        [](const Entry& entry, std::string_view wanted) {')
    lines.append('                                            return entry.key < wanted;')
    lines.append('                                        });')
    lines.append('    if (found == entries.end() || found->key != key) {')
    lines.append('        return std::nullopt;')
    lines.append('    }')
    lines.append('    return std::span<const unsigned char>(found->data, found->size);')
    lines.append('}')
    lines.append('}  // namespace realm::assets')
    text = '\n'.join(lines) + '\n'
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.is_file() or args.output.read_text() != text:
        args.output.write_text(text)
    print(f'Embedded {len(entries)} game assets ({sum(sizes)} bytes)')


if __name__ == '__main__':
    main()
