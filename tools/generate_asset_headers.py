#!/usr/bin/env python3
"""Generate the native asset headers from assets/manifest.json (written by tools/sync_game_assets.py).

Writes flash_assets.hpp (the asset table, image sets, animated sets, packet and stat IDs, data files and the source
identity) and source_inventory.json (the table data that compile_models.py and compile_particle_palettes.py read).
The build needs the manifest and the vendored files only; it never reads a Flash source tree.
"""
import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def inventory(manifest_path, manifest):
    """The table data the model and palette generators read, with paths relative to the assets directory."""
    if manifest.get('schema') != 1:
        raise ValueError(f'Unsupported manifest schema in {manifest_path}')
    source = manifest['source']
    return dict(revision=source['revision'], dirty=source['dirty'], source_sha256=source['source_sha256'],
                source_root=str(manifest_path.parent.resolve()),
                actionscript_files=source['actionscript_files'],
                assets=[dict(path=image['file'], width=image['width'], height=image['height'])
                        for image in manifest['images']],
                sheets=manifest['sheets'], animated=manifest['animated'],
                packets=manifest['packets'], stats=manifest['stats'], string_stats=manifest['string_stats'],
                data_files=manifest['data_files'],
                models=[dict(name=model['name'], path=model['file']) for model in manifest['models']])


def header(data, runtime_root):
    quote = lambda x: json.dumps(x, ensure_ascii=True)
    lines = ['// Generated by tools/generate_asset_headers.py from assets/manifest.json. Do not edit.', '#pragma once',
             '#include <array>', '#include <cstdint>', '#include <string_view>',
             'namespace realm::flash {',
             f'inline constexpr std::string_view revision = {quote(data["revision"])};',
             f'inline constexpr std::string_view assets_root = {quote(runtime_root)};',
             f'inline constexpr std::string_view source_sha256 = {quote(data["source_sha256"])};',
             'struct Asset { std::string_view path; int width, height; };',
             'struct Sheet { std::string_view name; int asset, width, height, count; };',
             'struct DataFile { std::string_view kind, path; };',
             'struct AnimatedSheet { std::string_view name; int asset, mask, width, height, strip_width, strip_height, first; };']
    for enum, items in [('PacketId', data['packets']), ('StatId', data['stats'])]:
        lines.append(f'enum class {enum} : std::uint8_t {{')
        lines.extend(f'    {name} = {value},' for name, value in items.items())
        lines.append('};')
    lines.append(f'inline constexpr std::array<Asset, {len(data["assets"])}> assets = {{{{')
    lines.extend(f'    {{{quote(a["path"])}, {a["width"]}, {a["height"]}}},' for a in data['assets'])
    lines.append('}};')
    lines.append(f'inline constexpr std::array<DataFile, {len(data["data_files"])}> data_files = {{{{')
    lines.extend(f'    {{{quote(d["kind"])}, {quote(d["file"])}}},' for d in data['data_files'])
    lines.append('}};')
    lines.append(f'inline constexpr std::array<Sheet, {len(data["sheets"])}> sheets = {{{{')
    lines.extend(f'    {{{quote(s["name"])}, {s["asset"]}, {s["width"]}, {s["height"]}, {s["count"]}}},'
                 for s in data['sheets'])
    lines.append('}};')
    lines.append(f'inline constexpr std::array<AnimatedSheet, {len(data["animated"])}> animated = {{{{')
    lines.extend('    {' + ', '.join([quote(s['name'])] + [str(s[k]) for k in
                 ['asset', 'mask', 'width', 'height', 'strip_width', 'strip_height']] +
                 ['0' if s['first'] == 'RIGHT' else '2']) + '},'
                 for s in data['animated'])
    lines.append('}};')
    lines.append(f'inline constexpr std::array<std::uint8_t, {len(data["string_stats"])}> string_stats = '
                 '{' + ', '.join(map(str, data['string_stats'])) + '};')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--manifest', type=Path, default=REPO / 'assets/manifest.json')
    parser.add_argument('--runtime-root', default='embedded:',
                        help='assets root compiled into flash_assets.hpp as flash::assets_root (default: embedded:)')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    manifest = json.loads(args.manifest.read_text())
    data = inventory(args.manifest, manifest)
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'flash_assets.hpp').write_text(header(data, args.runtime_root))
    (args.output / 'source_inventory.json').write_text(json.dumps(data, indent=2) + '\n')
    print(f"Assets {data['revision'][:12]}: {len(data['assets'])} images, {len(data['sheets'])} image sets, "
          f"{len(data['animated'])} animated sets, {len(data['models'])} models, {len(data['packets'])} packet IDs")


if __name__ == '__main__':
    main()
